function iconFor(entry, fallback) {
  const slugBase = (entry.slug || '').split('/').pop().replace(/\.html$/, '');
  const hay = ((entry.title || '') + ' ' + slugBase).toLowerCase();
  for (const [re, name] of RULES) {
    if (re.test(hay) && ICONS[name]) return ICONS[name];
  }
  return fallback;
}

module.exports = { ICONS, RULES, iconFor };
